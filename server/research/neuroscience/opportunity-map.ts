export interface RoutedNeuroRecord {
  readonly record: NeuroRecord;
  readonly presentation: NeuroPresentation;
}

/** Every record with the surface it routes to. The one place a surface should read. */
export function routeNeuroRecords(
  records: readonly NeuroRecord[] = NEUROSCIENCE_OPPORTUNITY_MAP,
): readonly RoutedNeuroRecord[] {
  return records.map((record) => ({ record, presentation: resolveNeuroPresentation(record) }));
}

/**
 * The records that may present as an offer on a Research surface right now.
 *
 * Empty today, and that is the correct answer, not a bug.
 */
export function offerableNeuroRecords(
  records: readonly NeuroRecord[] = NEUROSCIENCE_OPPORTUNITY_MAP,
): readonly NeuroRecord[] {
  return records.filter(mayPresentAsOffer);
}

