// Scientific Sean is a DISCOVERY SOURCE. It tells us what categories and items
// exist in this space and where our coverage has gaps. It is not a supplier, not
// a price list, and not a source of truth about legality, rights, or safety.
// Nothing here copies its images, labels, certificates, product text, or any
// other proprietary content. The category and vendor tables below record only
// observable coverage counts and the review action Xenios has to take.
//
// Every one of the 120 rows carries Status "Review" and the source context
// sentence naming the discovery source. None of them carries verification
// evidence. So every row imports UNVERIFIED, with all six verification inputs
// null, and `mayPresentAsOffer` is false for all 120. That is enforced by test,
// not by convention.
//
// The workbook's own boundary sentence appears verbatim on every record:
// benefits, dosing, and personal recommendations are not published without
// approved evidence and an approved route. Nothing in this module carries a
// dose, an administration instruction, or a claim.

