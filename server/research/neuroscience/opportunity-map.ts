/** How many rows each classification rule decided, so an odd rule shows up. */
export function classificationRuleHistogram(
  records: readonly NeuroRecord[] = NEUROSCIENCE_OPPORTUNITY_MAP,
): Readonly<Record<string, number>> {
  const counts: Record<string, number> = {};
  for (const record of records) {
    counts[record.classificationRuleId] = (counts[record.classificationRuleId] ?? 0) + 1;
  }
  return counts;
}
