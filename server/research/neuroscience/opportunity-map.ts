/**
 * Turn a transcribed row into a classified record.
 *
 * Classification comes from the ordered rule set in the shared contract.
 * Verification does not come from the sheet at all: there is no verification
 * evidence in it, so every record gets `UNVERIFIED` and null commerce fields.
 * A price, a supplier code, or a lab document can only arrive later, from a
 * document somebody recorded.
 */
export function toNeuroRecord(row: NeuroSourceRow): NeuroRecord {
  const classification = classifyNeuroRow({
    sourceClass: row.sourceClass,
    sourceRoute: row.sourceRoute,
    sourceLane: row.sourceLane,
  });
  return {
    id: row.id,
    item: row.item,
    sourceClass: row.sourceClass,
    sourceRoute: row.sourceRoute,
    sourceLane: row.sourceLane,
    operatingClass: classification.operatingClass,
    classificationRuleId: classification.ruleId,
    discoverySource: row.discoverySource,
    requiredProfessionalReview: row.requiredProfessionalReview,
    publicBoundary: row.publicBoundary,
    verification: UNVERIFIED,
    approvedCustomerAmountCents: null,
    supplierSkuCode: null,
    internalVariantSku: null,
    coaEvidence: "NOT_ON_FILE",
    unavailable: false,
  };
}

/** The 120 imported neuroscience records, classified and unverified. */
export const NEUROSCIENCE_OPPORTUNITY_MAP: readonly NeuroRecord[] =
  NEURO_SOURCE_ROWS.map(toNeuroRecord);

export function findNeuroRecord(id: string): NeuroRecord | undefined {
  return NEUROSCIENCE_OPPORTUNITY_MAP.find((record) => record.id === id);
}

export function neuroRecordsByClass(
  operatingClass: NeuroOperatingClass,
  records: readonly NeuroRecord[] = NEUROSCIENCE_OPPORTUNITY_MAP,
): readonly NeuroRecord[] {
  return records.filter((record) => record.operatingClass === operatingClass);
}

