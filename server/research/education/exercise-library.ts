// ---------------------------------------------------------------------------
// Sensitive subject detection
// ---------------------------------------------------------------------------

/**
 * Keyword rules that raise the review bar.
 *
 * IMPORTANT SCOPE NOTE. This scanner reads only the SUBJECT fields of a record:
 * the title, the source category, and the purpose. It deliberately never reads
 * the escalation note. Every row's escalation note names pain, dizziness, and
 * neurologic symptoms, because that is what an escalation note is for. Scanning
 * it would flag all 100 rows as neurological content and make the signal
 * meaningless.
 *
 * The rules cover exactly the five subjects the build directive names: injury,
 * surgery, pain, neurological limitation, rehabilitation. `youth`,
 * `pregnancy_postpartum`, and `product_or_care_linked` are NOT derived from
 * text. They describe who a lesson is for and what it is attached to, which is
 * an editorial decision, not something a keyword can settle. Deriving them from
 * a title also misreads ordinary movement names: "Child Pose Reach" is a yoga
 * posture, not youth content. A scanner that flagged it would teach reviewers
 * to ignore the flag.
 */
const SENSITIVE_SUBJECT_RULES: readonly {
  subject: EducationSensitiveSubject;
  pattern: RegExp;
}[] = [
  { subject: "injury", pattern: /\b(?:injur\w*|sprain\w*|strain\w*|tear|torn|acl|rotator cuff)\b/i },
  { subject: "surgery", pattern: /\b(?:surg\w*|post[- ]?op\w*|operative|arthroplasty|replacement)\b/i },
  { subject: "pain", pattern: /\b(?:pain|painful|ache|aching|sciatica)\b/i },
  {
    subject: "neurological_limitation",
    pattern: /\b(?:neurolog\w*|neuropath\w*|stroke|parkinson\w*|multiple sclerosis|spinal cord)\b/i,
  },
  {
    subject: "rehabilitation",
    pattern: /\b(?:rehab\w*|physical therapy|physio\w*|return[- ]to[- ]play|reconditioning)\b/i,
  },
];

/**
 * The subjects this scanner is able to derive. The remaining sensitive subjects
 * are set editorially. Exported so a test can pin the split.
 */
export const TEXT_DERIVED_SENSITIVE_SUBJECTS: readonly EducationSensitiveSubject[] =
  SENSITIVE_SUBJECT_RULES.map((rule) => rule.subject);

/**
 * Derive the sensitive subjects a record carries from its subject text.
 *
 * This is a floor, not a ceiling. An editor may add any sensitive subject to a
 * record; the scanner exists so that obvious injury, surgery, pain,
 * neurological, and rehabilitation content cannot slip through unflagged.
 */
export function deriveSensitiveSubjects(
  ...subjectFields: readonly string[]
): readonly EducationSensitiveSubject[] {
  const found: EducationSensitiveSubject[] = [];
  for (const rule of SENSITIVE_SUBJECT_RULES) {
    if (subjectFields.some((field) => rule.pattern.test(field ?? ""))) {
      if (!found.includes(rule.subject)) found.push(rule.subject);
    }
  }
  return found;
}

