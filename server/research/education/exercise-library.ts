/** Values the workbook uses to mean "not done yet". Never carried into a record. */
const PLACEHOLDER_NOTES = new Set([
  "professional reviewer pending",
  "script draft",
  "video needed",
  "transcript needed",
  "tags needed",
]);

function isPlaceholderNote(value: string): boolean {
  return PLACEHOLDER_NOTES.has(value.trim().toLowerCase());
}

/**
 * Turn a transcribed row into a library record.
 *
 * Every placeholder becomes a null or an empty list. Nothing is upgraded.
 */
export function toEducationRecord(row: ExerciseSourceRow): EducationRecord {
  return {
    id: row.id,
    title: row.title,
    contentType: "general_exercise_demonstration",
    // The workbook assigns no per record audience. It stays null, and the gate
    // reports it as a blocker, rather than being invented from the scope banner.
    audience: null,
    movementPattern: row.movementPattern,
    equipment: row.equipment,
    difficulty: row.difficulty,
    sensitiveSubjects: deriveSensitiveSubjects(row.title, row.sourceCategory, row.purpose),
    escalationNote: row.escalationNote,
    author: row.author,
    // "Professional reviewer pending" is a placeholder, not a reviewer.
    reviews: [],
    transcript: isPlaceholderNote(row.sourceTranscriptNote) ? null : row.sourceTranscriptNote,
    media: null,
    scriptBody: isPlaceholderNote(row.sourceScriptNote) ? null : row.sourceScriptNote,
    approvalState: row.sourceStatus.trim().toLowerCase() === "draft" ? "DRAFT" : "IN_REVIEW",
    reviewDate: null,
    version: 1,
    tags: isPlaceholderNote(row.sourceTagsNote) ? [] : [row.sourceTagsNote],
  };
}

/** The 100 imported exercise records, as the library holds them today. */
export const EXERCISE_LIBRARY: readonly EducationRecord[] =
  EXERCISE_SOURCE_ROWS.map(toEducationRecord);

export function findEducationRecord(id: string): EducationRecord | undefined {
  return EXERCISE_LIBRARY.find((record) => record.id === id);
}

/**
 * The records a surface may actually show.
 *
 * There is no "show the drafts anyway" option. A record reaches a learner only
 * through the shared publication gate.
 */
export function publishedEducationRecords(
  records: readonly EducationRecord[] = EXERCISE_LIBRARY,
): readonly EducationRecord[] {
  return records.filter((record) => evaluatePublication(record).publishable);
}

