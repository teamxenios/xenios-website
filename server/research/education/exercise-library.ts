/** How often each blocker code appears across the library, for an operations queue. */
export function blockerHistogram(
  records: readonly EducationRecord[] = EXERCISE_LIBRARY,
): Readonly<Record<string, number>> {
  const counts: Record<string, number> = {};
  for (const record of records) {
    const seen = new Set<string>();
    for (const blocker of evaluatePublication(record).blockers as readonly PublicationBlocker[]) {
      if (seen.has(blocker.code)) continue;
      seen.add(blocker.code);
      counts[blocker.code] = (counts[blocker.code] ?? 0) + 1;
    }
  }
  return counts;
}
