// xenios education library: the imported exercise records.
//
// SERVER SIDE. This module holds the production tracker exactly as the source
// workbook states it, including the fields that are still empty. Surfaces read
// `EXERCISE_LIBRARY` through the shared publication gate, never around it.
//
// ---------------------------------------------------------------------------
// Where the data comes from
// ---------------------------------------------------------------------------
//
//   - `XENIOS_RESEARCH_COMPLETE_MASTER_2026-08-01_V3.xlsx`, sheet
//     "43 Education Exercise". 103 sheet rows: a title banner, a scope sentence,
//     a header row, and 100 exercise rows, EX-0001 to EX-0100.
//   - The same rows appear in `13_EDUCATION_EXERCISE_AND_LEARNING_LIBRARY_2026-08-01_v2.xlsx`,
//     sheet "Exercise Library". That workbook also carries sheet "Approval Matrix",
//     rows ED-AP-001 to ED-AP-010, transcribed below as `EDUCATION_APPROVAL_MATRIX`.
//
// Every field below is a transcription. Nothing was inferred from an exercise
// name, and no missing field was filled in.
//
// ---------------------------------------------------------------------------
// What the workbook actually says, and what that means here
// ---------------------------------------------------------------------------
//
// All 100 rows carry the same four placeholder values:
//
//   Reviewer   "Professional reviewer pending"  -> zero recorded reviews
//   Video      "Video needed"                   -> media is null
//   Transcript "Transcript needed"              -> transcript is null
//   Tags       "Tags needed"                    -> tags is empty
//
// and Status "Draft". A placeholder is not evidence. `isRealValue` in the shared
// contract rejects every one of these phrases, so none of them can be mistaken
// for a reviewer, an asset, or a transcript. The library is therefore complete in
// structure and empty in approvals, which is the truthful state.
//
// Afam Maduka is the named AUTHOR on all 100 rows, transcribed from the author
// column. He has not reviewed anything here, and no review by him or by anyone
// else is recorded in this build.
//
// The workbook assigns no per record audience, so `audience` is null on every
// record and every record carries the MISSING_AUDIENCE blocker. The library level
// scope sentence is transcribed as `LIBRARY_SCOPE_STATEMENT` rather than being
// converted into a per record audience value we were never given.

