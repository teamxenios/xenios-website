import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawn,spawnSync} from 'node:child_process';
const [label,...args]=process.argv.slice(2);
if(!/^[a-z0-9-]+$/.test(label||'')||args.length===0)throw Error('label and node arguments required');
const directory=path.resolve('docs/health-launch/quick-order-20261005/evidence');
const output=path.join(directory,`${label}.log`),receipt=path.join(directory,`${label}.json`);
if(fs.existsSync(output)||fs.existsSync(receipt))throw Error('Evidence must not be overwritten');
const git=(...argv)=>spawnSync('git',argv,{encoding:'utf8'}).stdout.trim();
const sourceFiles=()=>git('ls-files','--','client/src/quick-order','server/health/quick-order').split('\n').filter(Boolean).sort();
const sources=()=>sourceFiles().map(file=>({path:file,sha256lf:crypto.createHash('sha256').update(fs.readFileSync(file,'utf8').replaceAll('\r\n','\n')).digest('hex')}));
const state=()=>({head:git('rev-parse','HEAD'),tree:git('rev-parse','HEAD^{tree}'),dirty:git('status','--porcelain','--untracked-files=normal'),sources:sources()});
const before=state(),start=new Date().toISOString();
const fd=fs.openSync(output,'wx');
const child=spawn(process.execPath,args,{cwd:process.cwd(),env:{...process.env,PATH:`${path.dirname(process.execPath)};${process.env.PATH}`,NODE_OPTIONS:'--max-old-space-size=1024'},stdio:['ignore','pipe','pipe']});
child.stdout.on('data',b=>fs.writeSync(fd,b));child.stderr.on('data',b=>fs.writeSync(fd,b));
child.on('error',e=>fs.writeSync(fd,String(e)));
const exit=await new Promise(resolve=>child.on('close',(code,signal)=>resolve({code,signal})));
fs.closeSync(fd);
const bytes=fs.readFileSync(output),finished=new Date().toISOString(),after=state();
const sourcesUnchanged=JSON.stringify(before.sources)===JSON.stringify(after.sources);
const data={label,start,finished,node:process.version,executable:process.execPath,args,cwd:process.cwd(),childPid:child.pid,exit,before,after,sourcesUnchanged,logSha256:crypto.createHash('sha256').update(bytes).digest('hex'),logBytes:bytes.length,provenance:'Pinned launcher executable and before/after tracked Quick Order source hashes; no continuous process or filesystem attestation.'};
fs.writeFileSync(receipt,JSON.stringify(data,null,2)+'\n');
console.log(JSON.stringify({...data,before:{head:before.head,dirty:!!before.dirty},after:{head:after.head,dirty:!!after.dirty}}));
console.log(bytes.toString('utf8').split('\n').slice(-12).join('\n'));
process.exitCode=sourcesUnchanged ? exit.code ?? 1 : 1;
