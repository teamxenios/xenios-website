  telehealth_consent_event_id, privacy_consent_event_id
on public.care_intakes
for each row execute function public.care_validate_intake_bindings();

create or replace function public.care_intake_autosave(
  p_intake_id uuid,
  p_patient_id uuid,
  p_expected_version integer,
  p_responses jsonb,
  p_idempotency_key text,
  p_occurred_at timestamptz
)
returns public.care_intake_revisions
language plpgsql
set search_path = ''
as $$
declare
  intake_row public.care_intakes%rowtype;
  revision_row public.care_intake_revisions%rowtype;
begin
  select * into intake_row
  from public.care_intakes
  where id = p_intake_id
  for update;

  if not found
    or intake_row.patient_id <> p_patient_id
    or intake_row.status <> 'draft' then
    raise exception 'care_intake_not_editable'
      using errcode = '42501';
  end if;
  if not exists (
    select 1
    from public.care_consent_events event
    join public.care_consent_documents document
      on document.id = event.document_id
     and document.kind = event.kind
     and document.version = event.document_version
    where event.id = intake_row.telehealth_consent_event_id
      and event.patient_id = p_patient_id
      and event.kind = 'telehealth'
      and event.action = 'granted'
      and document.status = 'approved'
      and document.approved_at is not null
      and document.effective_at is not null
      and event.id = (
        select latest.id
        from public.care_consent_events latest
        where latest.patient_id = p_patient_id
          and latest.kind = 'telehealth'
        order by latest.occurred_at desc, latest.id desc
        limit 1
      )
  ) then
    raise exception 'care_intake_consent_required'
      using errcode = '23514';
  end if;
  if not exists (
    select 1
    from public.care_consent_events event
    join public.care_consent_documents document
      on document.id = event.document_id
     and document.kind = event.kind
     and document.version = event.document_version
    where event.id = intake_row.privacy_consent_event_id
      and event.patient_id = p_patient_id
      and event.kind = 'privacy_notice'
      and event.action = 'granted'
      and document.status = 'approved'
      and document.approved_at is not null
      and document.effective_at is not null
      and event.id = (
        select latest.id
        from public.care_consent_events latest
        where latest.patient_id = p_patient_id
          and latest.kind = 'privacy_notice'
        order by latest.occurred_at desc, latest.id desc
        limit 1
      )
  ) then
    raise exception 'care_intake_consent_required'
      using errcode = '23514';
  end if;

  select * into revision_row
  from public.care_intake_revisions
  where patient_id = p_patient_id
    and idempotency_key = p_idempotency_key;
  if found then
    return revision_row;
  end if;

  if intake_row.version <> p_expected_version then
    raise exception 'care_intake_version_conflict'
      using errcode = '40001';
  end if;
  if not exists (
    select 1
    from public.care_intake_definitions definition
    where definition.id = intake_row.definition_id
      and definition.version = intake_row.definition_version
      and definition.status = 'approved'
      and definition.approved_at is not null
  ) then
    raise exception 'care_intake_definition_unavailable'
      using errcode = '23514';
  end if;
  if jsonb_typeof(p_responses) <> 'object' then
    raise exception 'care_intake_invalid_responses'
      using errcode = '22023';
  end if;

  insert into public.care_intake_revisions (
    intake_id,
    patient_id,
    version,
    responses,
    idempotency_key,
    created_at
  )
  values (
    p_intake_id,
    p_patient_id,
    intake_row.version + 1,
    p_responses,
    p_idempotency_key,
    p_occurred_at
  )
  returning * into revision_row;

  update public.care_intakes
  set version = revision_row.version
  where id = p_intake_id;

  return revision_row;
end;
$$;

create or replace function public.care_intake_submit(
  p_intake_id uuid,
  p_patient_id uuid,
  p_expected_version integer,
  p_idempotency_key text,
  p_occurred_at timestamptz
)
returns public.care_intakes
language plpgsql
set search_path = ''
as $$
declare
  intake_row public.care_intakes%rowtype;
begin
  select * into intake_row
  from public.care_intakes
  where id = p_intake_id
  for update;

  if not found or intake_row.patient_id <> p_patient_id then
    raise exception 'care_intake_not_found'
      using errcode = '42501';
  end if;
  if not exists (
    select 1
    from public.care_consent_events event
    join public.care_consent_documents document
      on document.id = event.document_id
     and document.kind = event.kind
     and document.version = event.document_version
    where event.id = intake_row.telehealth_consent_event_id
      and event.patient_id = p_patient_id
      and event.kind = 'telehealth'
      and event.action = 'granted'
      and document.status = 'approved'
      and document.approved_at is not null
      and document.effective_at is not null
      and event.id = (
        select latest.id
        from public.care_consent_events latest
        where latest.patient_id = p_patient_id
          and latest.kind = 'telehealth'
        order by latest.occurred_at desc, latest.id desc
        limit 1
      )
  ) then
    raise exception 'care_intake_consent_required'
      using errcode = '23514';
  end if;
  if not exists (
    select 1
    from public.care_consent_events event
    join public.care_consent_documents document
      on document.id = event.document_id
     and document.kind = event.kind
     and document.version = event.document_version
    where event.id = intake_row.privacy_consent_event_id
      and event.patient_id = p_patient_id
      and event.kind = 'privacy_notice'
      and event.action = 'granted'
      and document.status = 'approved'
      and document.approved_at is not null
      and document.effective_at is not null
      and event.id = (
        select latest.id
        from public.care_consent_events latest
        where latest.patient_id = p_patient_id
          and latest.kind = 'privacy_notice'
        order by latest.occurred_at desc, latest.id desc
        limit 1
      )
  ) then
    raise exception 'care_intake_consent_required'
      using errcode = '23514';
  end if;
  if intake_row.status = 'submitted'
    and intake_row.submit_idempotency_key = p_idempotency_key then
    return intake_row;
  end if;
  if intake_row.status <> 'draft' then
    raise exception 'care_intake_not_submittable'
      using errcode = '55000';
  end if;
  if intake_row.version <> p_expected_version then
    raise exception 'care_intake_version_conflict'
      using errcode = '40001';
  end if;
  if not exists (
    select 1
    from public.care_intake_definitions definition
    where definition.id = intake_row.definition_id
      and definition.version = intake_row.definition_version
      and definition.status = 'approved'
      and definition.approved_at is not null
  ) then
    raise exception 'care_intake_definition_unavailable'
      using errcode = '23514';
  end if;
  if not exists (
    select 1
    from public.care_intake_revisions revision
    where revision.intake_id = p_intake_id
      and revision.patient_id = p_patient_id
      and revision.version = intake_row.version
  ) then
    raise exception 'care_intake_has_no_current_revision'
      using errcode = '23514';
  end if;

  update public.care_intakes
  set
    status = 'submitted',
    submit_idempotency_key = p_idempotency_key,
    submitted_at = p_occurred_at
  where id = p_intake_id
  returning * into intake_row;

  return intake_row;
end;
$$;

