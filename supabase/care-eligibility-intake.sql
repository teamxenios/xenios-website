-- Xenios Care PR 2: location, state/clinician coverage, consent, waitlist,
-- and independently versioned clinical-intake foundation.
--
-- Additive and idempotent. This migration seeds no supported state, clinician,
-- consent document, intake definition, medical question, or patient record.
-- All browser roles are denied; production access is through the authorized
-- Care server boundary and Supabase service role.

create extension if not exists pgcrypto;

create table if not exists public.care_patients (
  id uuid primary key default gen_random_uuid(),
  user_id uuid null unique references auth.users(id) on delete set null,
  identity_state text not null default 'unverified'
    check (identity_state in ('unverified', 'pending', 'verified', 'rejected')),
  identity_verified_at timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    identity_state <> 'verified'
    or identity_verified_at is not null
  )
);

create table if not exists public.care_patient_locations (
  id uuid primary key default gen_random_uuid(),
  patient_id uuid not null references public.care_patients(id) on delete cascade,
  state_code text not null check (state_code ~ '^[A-Z]{2}$'),
  source text not null
    check (source in ('patient_attestation', 'approved_identity_provider')),
  attested_at timestamptz not null default now(),
  supersedes_location_id uuid null
    references public.care_patient_locations(id),
  idempotency_key text not null check (length(idempotency_key) between 8 and 128),
  unique (patient_id, idempotency_key),
  check (supersedes_location_id is null or supersedes_location_id <> id)
);

create table if not exists public.care_supported_states (
  state_code text primary key check (state_code ~ '^[A-Z]{2}$'),
  supported_state_active boolean not null default false,
  service_coverage_active boolean not null default false,
  waitlist_enabled boolean not null default false,
  approved_by uuid null references auth.users(id),
  approved_at timestamptz null,
  updated_at timestamptz not null default now(),
  check (
    not (supported_state_active or service_coverage_active or waitlist_enabled)
    or (approved_by is not null and approved_at is not null)
  ),
  check (not service_coverage_active or supported_state_active)
);

create table if not exists public.care_supported_state_audit (
  id bigint generated by default as identity primary key,
  state_code text not null check (state_code ~ '^[A-Z]{2}$'),
  action text not null check (action in ('insert', 'update', 'delete')),
  old_record jsonb null,
  new_record jsonb null,
  changed_by uuid null,
  occurred_at timestamptz not null default now()
);

create table if not exists public.care_clinician_state_coverage (
  id uuid primary key default gen_random_uuid(),
  clinician_user_id uuid not null references auth.users(id) on delete cascade,
  state_code text not null references public.care_supported_states(state_code),
  active boolean not null default false,
  verified_by uuid null references auth.users(id),
  verified_at timestamptz null,
  expires_at timestamptz null,
  created_at timestamptz not null default now(),
  check (
    not active
    or (verified_by is not null and verified_at is not null)
  ),
  check (expires_at is null or verified_at is null or expires_at > verified_at)
);

create unique index if not exists care_clinician_state_active_idx
  on public.care_clinician_state_coverage (clinician_user_id, state_code)
  where active;

create table if not exists public.care_clinician_coverage_audit (
  id bigint generated by default as identity primary key,
  coverage_id uuid not null,
  clinician_user_id uuid null,
  state_code text not null check (state_code ~ '^[A-Z]{2}$'),
  action text not null check (action in ('insert', 'update', 'delete')),
  old_record jsonb null,
  new_record jsonb null,
  changed_by uuid null,
  occurred_at timestamptz not null default now()
);

create or replace function public.care_validate_clinician_coverage()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.active and not exists (
    select 1
    from public.care_role_assignments assignment
    where assignment.user_id = new.clinician_user_id
      and assignment.role = 'clinician'
      and assignment.revoked_at is null
  ) then
    raise exception 'care_active_clinician_role_required'
      using errcode = '23514';
  end if;
  return new;
end;
$$;

revoke all on function public.care_validate_clinician_coverage()
  from public, anon, authenticated;

