create or replace function public.care_active_clinician_count(
  p_state_code text,
  p_as_of timestamptz default now()
)
returns integer
language sql
stable
set search_path = ''
as $$
  select count(distinct coverage.clinician_user_id)::integer
  from public.care_clinician_state_coverage coverage
  join public.care_role_assignments assignment
    on assignment.user_id = coverage.clinician_user_id
    and assignment.role = 'clinician'
    and assignment.revoked_at is null
  where coverage.state_code = p_state_code
    and coverage.active
    and (coverage.expires_at is null or coverage.expires_at > p_as_of);
$$;

revoke all on function public.care_active_clinician_count(text, timestamptz)
  from public, anon, authenticated;
grant execute on function public.care_active_clinician_count(text, timestamptz)
  to service_role;

create or replace function public.care_audit_clinician_coverage_change()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  insert into public.care_clinician_coverage_audit (
    coverage_id,
    clinician_user_id,
    state_code,
    action,
    old_record,
    new_record,
    changed_by
  )
  values (
    coalesce(new.id, old.id),
    coalesce(new.clinician_user_id, old.clinician_user_id),
    coalesce(new.state_code, old.state_code),
    lower(tg_op),
    case when tg_op = 'INSERT' then null else to_jsonb(old) end,
    case when tg_op = 'DELETE' then null else to_jsonb(new) end,
    coalesce(new.verified_by, old.verified_by)
  );
  return coalesce(new, old);
end;
$$;

