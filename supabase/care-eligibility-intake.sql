create or replace function public.care_validate_intake_bindings()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  definition_row public.care_intake_definitions%rowtype;
  telehealth_event public.care_consent_events%rowtype;
  privacy_event public.care_consent_events%rowtype;
begin
  select * into definition_row
  from public.care_intake_definitions
  where id = new.definition_id;

  if definition_row.status <> 'approved'
    or definition_row.approved_at is null
    or definition_row.version <> new.definition_version then
    raise exception 'care_intake_definition_unavailable'
      using errcode = '23514';
  end if;

  select * into telehealth_event
  from public.care_consent_events
  where id = new.telehealth_consent_event_id;
  select * into privacy_event
  from public.care_consent_events
  where id = new.privacy_consent_event_id;

  if telehealth_event.patient_id <> new.patient_id
    or telehealth_event.kind <> 'telehealth'
    or telehealth_event.action <> 'granted' then
    raise exception 'care_telehealth_consent_mismatch'
      using errcode = '23514';
  end if;
  if privacy_event.patient_id <> new.patient_id
    or privacy_event.kind <> 'privacy_notice'
    or privacy_event.action <> 'granted' then
    raise exception 'care_privacy_consent_mismatch'
      using errcode = '23514';
  end if;
  return new;
end;
$$;

revoke all on function public.care_validate_intake_bindings()
  from public, anon, authenticated;

drop trigger if exists care_intake_binding_guard on public.care_intakes;
create trigger care_intake_binding_guard
