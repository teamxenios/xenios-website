create or replace function public.care_guard_consent_document_version()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    if old.status <> 'draft' then
      raise exception 'care_approved_consent_document_immutable'
        using errcode = '55000';
    end if;
    return old;
  end if;

  if old.status = 'superseded' then
    if to_jsonb(new) is distinct from to_jsonb(old) then
      raise exception 'care_superseded_consent_document_immutable'
        using errcode = '55000';
    end if;
  elsif old.status = 'approved' then
    if new.status = 'superseded'
      and new.superseded_at is not null
      and new.id = old.id
      and new.kind = old.kind
      and new.version = old.version
      and new.content_hash = old.content_hash
      and new.approved_by is not distinct from old.approved_by
      and new.approved_at is not distinct from old.approved_at
      and new.effective_at is not distinct from old.effective_at
      and new.created_at = old.created_at then
      return new;
    end if;
    if to_jsonb(new) is distinct from to_jsonb(old) then
      raise exception 'care_approved_consent_document_immutable'
        using errcode = '55000';
    end if;
  end if;
  return new;
end;
$$;

