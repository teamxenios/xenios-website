-- Xenios Care PR 5: patient instruction and supply-kit foundation.
--
-- Additive and idempotent. Seeds no instruction, source, device, supplier,
-- replacement, patient, prescription, pharmacy, or clinical fact. It invokes
-- no external action and leaves Care disabled.

create extension if not exists pgcrypto;

create table if not exists public.care_instruction_sources (
  id uuid primary key default gen_random_uuid(),
  patient_id uuid null references public.care_patients(id) on delete cascade,
  prescription_id uuid null references public.care_prescriptions(id),
  kind text not null check (kind in (
    'pharmacy_label', 'pharmacy_information', 'clinician_direction',
    'manufacturer_material', 'general_education'
  )),
  version integer not null check (version > 0),
  source_reference text not null check (nullif(trim(source_reference), '') is not null),
  content_hash text not null check (nullif(trim(content_hash), '') is not null),
  content text not null check (nullif(trim(content), '') is not null),
  verification_state text not null default 'verified'
    check (verification_state in ('verified', 'rejected', 'expired', 'superseded')),
  verified_by uuid not null references auth.users(id),
  verified_at timestamptz not null,
  supersedes_source_id uuid null references public.care_instruction_sources(id),
  idempotency_key text not null check (length(idempotency_key) between 8 and 128),
  created_at timestamptz not null default now(),
  unique (verified_by, idempotency_key),
  check (
    (kind = 'general_education' and patient_id is null and prescription_id is null)
    or
    (kind <> 'general_education' and patient_id is not null and prescription_id is not null)
  ),
  check (supersedes_source_id is null or supersedes_source_id <> id)
);

create index if not exists care_instruction_sources_prescription_idx
  on public.care_instruction_sources (prescription_id, kind, created_at desc)
  where prescription_id is not null;

create table if not exists public.care_patient_instructions (
  id uuid primary key default gen_random_uuid(),
  patient_id uuid not null references public.care_patients(id) on delete cascade,
  prescription_id uuid not null references public.care_prescriptions(id),
  prescribing_clinician_user_id uuid not null references auth.users(id),
  status text not null default 'draft'
    check (status in ('draft', 'released', 'superseded', 'withdrawn')),
  instruction_content text not null
    check (nullif(trim(instruction_content), '') is not null),
  version integer not null default 0 check (version >= 0),
  acknowledged_version integer null check (acknowledged_version is null or acknowledged_version >= 0),
  supersedes_instruction_id uuid null references public.care_patient_instructions(id),
  create_idempotency_key text not null check (length(create_idempotency_key) between 8 and 128),
  released_at timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (prescribing_clinician_user_id, create_idempotency_key),
  check (
    (status = 'draft' and released_at is null)
    or (status in ('released', 'superseded', 'withdrawn') and released_at is not null)
  ),
  check (supersedes_instruction_id is null or supersedes_instruction_id <> id)
);

create unique index if not exists care_patient_instruction_active_idx
  on public.care_patient_instructions (patient_id, prescription_id)
  where status = 'released';

create table if not exists public.care_instruction_source_links (
  instruction_id uuid not null references public.care_patient_instructions(id) on delete cascade,
  source_id uuid not null references public.care_instruction_sources(id),
  source_kind text not null check (source_kind in (
    'pharmacy_label', 'pharmacy_information', 'clinician_direction',
    'manufacturer_material'
  )),
  created_at timestamptz not null default now(),
  primary key (instruction_id, source_id),
  unique (instruction_id, source_kind)
);

create table if not exists public.care_instruction_events (
  id bigint generated by default as identity primary key,
  instruction_id uuid not null references public.care_patient_instructions(id) on delete cascade,
  patient_id uuid not null references public.care_patients(id) on delete cascade,
  actor_user_id uuid not null references auth.users(id),
  actor_kind text not null check (actor_kind in ('human_clinician', 'clinical_admin')),
  action text not null check (action in ('drafted', 'released', 'superseded', 'withdrawn')),
  from_status text null,
  to_status text not null,
  idempotency_key text not null check (length(idempotency_key) between 8 and 128),
  occurred_at timestamptz not null,
  unique (instruction_id, idempotency_key)
);

create table if not exists public.care_instruction_acknowledgments (
  id bigint generated by default as identity primary key,
  instruction_id uuid not null references public.care_patient_instructions(id) on delete cascade,
  patient_id uuid not null references public.care_patients(id) on delete cascade,
  instruction_version integer not null check (instruction_version > 0),
  idempotency_key text not null check (length(idempotency_key) between 8 and 128),
  acknowledged_at timestamptz not null,
  unique (patient_id, idempotency_key),
  unique (instruction_id, patient_id, instruction_version)
);

create table if not exists public.care_supply_sources (
  id uuid primary key default gen_random_uuid(),
  legal_name text null,
  relationship_reference text null,
  support_reference text null,
  verification_state text not null default 'missing'
    check (verification_state in (
      'missing', 'entered', 'under_review', 'verified', 'rejected',
      'expired', 'superseded'
    )),
  verified_by uuid null references auth.users(id),
  verified_at timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    verification_state <> 'verified'
    or (
      nullif(trim(legal_name), '') is not null
      and nullif(trim(relationship_reference), '') is not null
      and nullif(trim(support_reference), '') is not null
      and verified_by is not null and verified_at is not null
    )
  )
);

create table if not exists public.care_supply_configuration_audit (
  id bigint generated by default as identity primary key,
  supply_source_id uuid not null,
  action text not null check (action in ('insert', 'update', 'delete')),
  old_record jsonb null,
  new_record jsonb null,
  occurred_at timestamptz not null default now()
);

