create or replace function public.care_apply_supply_replacement_action(
  p_replacement_id uuid,
  p_actor_user_id uuid,
  p_expected_version integer,
  p_action text,
  p_idempotency_key text,
  p_occurred_at timestamptz
)
returns public.care_supply_replacements
language plpgsql
security definer
set search_path = ''
as $$
declare
  replacement_row public.care_supply_replacements%rowtype;
  kit_row public.care_supply_kits%rowtype;
  actor_kind text;
  next_status text;
begin
  if exists (
    select 1 from public.care_supply_replacement_events
    where replacement_id=p_replacement_id and idempotency_key=p_idempotency_key
  ) then
    select * into replacement_row from public.care_supply_replacements where id=p_replacement_id;
    return replacement_row;
  end if;
  select * into replacement_row from public.care_supply_replacements
    where id=p_replacement_id and version=p_expected_version;
  if not found then raise exception 'care_current_replacement_required' using errcode='23514'; end if;
  select * into kit_row from public.care_supply_kits where id=replacement_row.supply_kit_id;
  if exists (
    select 1 from public.care_role_assignments
    where user_id=p_actor_user_id and role='clinical_admin' and revoked_at is null
  ) then actor_kind := 'clinical_admin';
  elsif exists (
    select 1 from public.care_pharmacy_orders pharmacy_order
    join public.care_pharmacy_operators operator
      on operator.pharmacy_id=pharmacy_order.assigned_pharmacy_id
      and operator.user_id=p_actor_user_id and operator.active and operator.revoked_at is null
    join public.care_role_assignments assignment
      on assignment.user_id=operator.user_id and assignment.role='pharmacy_operations'
      and assignment.revoked_at is null
    where pharmacy_order.prescription_id=kit_row.prescription_id
  ) then actor_kind := 'pharmacy_operator';
  else raise exception 'care_replacement_operator_required' using errcode='42501'; end if;
  next_status := case p_action
    when 'approve' then 'approved'
    when 'fulfill' then 'fulfilled'
    when 'decline' then 'declined'
    when 'cancel' then 'cancelled'
    else null end;
  if next_status is null or not (
    (replacement_row.status='requested' and next_status in ('approved','declined','cancelled'))
    or (replacement_row.status='approved' and next_status in ('fulfilled','cancelled'))
  ) then raise exception 'care_invalid_replacement_transition' using errcode='23514'; end if;
  update public.care_supply_replacements set status=next_status,
    version=version+1,updated_at=p_occurred_at where id=p_replacement_id
    returning * into replacement_row;
  insert into public.care_supply_replacement_events (
    replacement_id,patient_id,actor_user_id,actor_kind,action,from_status,
    to_status,idempotency_key,occurred_at
  ) values (
    replacement_row.id,replacement_row.patient_id,p_actor_user_id,actor_kind,
    p_action,null,next_status,p_idempotency_key,p_occurred_at
  );
  return replacement_row;
end;
$$;

