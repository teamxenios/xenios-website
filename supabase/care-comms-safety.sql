create or replace function public.care_apply_lab_action(
  p_lab_case_id uuid,
  p_reviewer_user_id uuid,
  p_expected_version integer,
  p_action text,
  p_provider_reference text,
  p_order_reference text,
  p_result_reference text,
  p_secure_object_reference text,
  p_idempotency_key text,
  p_occurred_at timestamptz
)
returns public.care_lab_cases
language plpgsql
security definer
set search_path=''
as $$
declare lab_row public.care_lab_cases%rowtype;
declare next_status text;
declare previous_status text;
begin
  if exists (
    select 1 from public.care_lab_events
    where lab_case_id=p_lab_case_id and action=p_action
      and idempotency_key=p_idempotency_key
  ) then
    select * into lab_row from public.care_lab_cases where id=p_lab_case_id;
    return lab_row;
  end if;
  if not exists (
    select 1 from public.care_lab_assignments assignment
    join public.care_role_assignments role_assignment
      on role_assignment.user_id=assignment.reviewer_user_id
      and role_assignment.role='lab_reviewer'
      and role_assignment.revoked_at is null
    where assignment.lab_case_id=p_lab_case_id
      and assignment.reviewer_user_id=p_reviewer_user_id
      and assignment.revoked_at is null
  ) then raise exception 'care_assigned_lab_reviewer_required' using errcode='42501'; end if;
  select * into lab_row from public.care_lab_cases
    where id=p_lab_case_id and version=p_expected_version;
  if not found then raise exception 'care_current_lab_case_required' using errcode='23514'; end if;
  previous_status := lab_row.status;
  next_status := case p_action
    when 'record_order_reference' then 'order_reference_recorded'
    when 'record_result_reference' then 'result_reference_recorded'
    when 'review' then 'reviewed'
    when 'close' then 'closed'
    else null end;
  if next_status is null or not (
    (lab_row.status='awaiting_order_reference' and p_action='record_order_reference'
      and nullif(trim(p_provider_reference),'') is not null
      and nullif(trim(p_order_reference),'') is not null)
    or (lab_row.status='order_reference_recorded' and p_action='record_result_reference'
      and nullif(trim(p_result_reference),'') is not null
      and nullif(trim(p_secure_object_reference),'') is not null)
    or (lab_row.status='result_reference_recorded' and p_action='review')
    or (lab_row.status='reviewed' and p_action='close')
  ) then raise exception 'care_invalid_lab_transition' using errcode='23514'; end if;
  update public.care_lab_cases set
    status=next_status,
    provider_reference=case when p_action='record_order_reference'
      then p_provider_reference else provider_reference end,
    order_reference=case when p_action='record_order_reference'
      then p_order_reference else order_reference end,
    result_reference=case when p_action='record_result_reference'
      then p_result_reference else result_reference end,
    secure_object_reference=case when p_action='record_result_reference'
      then p_secure_object_reference else secure_object_reference end,
    reviewed_by=case when p_action='review' then p_reviewer_user_id else reviewed_by end,
    reviewed_at=case when p_action='review' then p_occurred_at else reviewed_at end,
    version=version+1,updated_at=p_occurred_at
    where id=p_lab_case_id returning * into lab_row;
  insert into public.care_lab_events (
    lab_case_id,patient_id,actor_user_id,actor_kind,action,from_status,to_status,
    idempotency_key,occurred_at
  ) values (
    lab_row.id,lab_row.patient_id,p_reviewer_user_id,'lab_reviewer',p_action,
    previous_status,next_status,p_idempotency_key,p_occurred_at
  );
  return lab_row;
end;
$$;

create or replace function public.care_report_adverse_event(
  p_patient_id uuid,
  p_patient_user_id uuid,
  p_category text,
  p_urgency text,
  p_summary text,
  p_emergency_guidance_acknowledged boolean,
  p_idempotency_key text,
  p_occurred_at timestamptz
)
returns public.care_adverse_events
language plpgsql
security definer
set search_path=''
as $$
declare event_row public.care_adverse_events%rowtype;
begin
  if not p_emergency_guidance_acknowledged then
    raise exception 'care_emergency_guidance_acknowledgment_required' using errcode='23514';
  end if;
  if not exists (
    select 1 from public.care_patients patient
    join public.care_role_assignments assignment
      on assignment.user_id=patient.user_id and assignment.role='care_patient'
      and assignment.revoked_at is null
    where patient.id=p_patient_id and patient.user_id=p_patient_user_id
  ) then raise exception 'care_patient_ownership_required' using errcode='42501'; end if;
  select * into event_row from public.care_adverse_events
    where patient_id=p_patient_id and report_idempotency_key=p_idempotency_key;
  if found then return event_row; end if;
  insert into public.care_adverse_events (
    patient_id,reporter_user_id,category,urgency,summary,
    emergency_guidance_acknowledged_at,report_idempotency_key,
    created_at,updated_at
  ) values (
    p_patient_id,p_patient_user_id,p_category,p_urgency,p_summary,
    p_occurred_at,p_idempotency_key,p_occurred_at,p_occurred_at
  ) returning * into event_row;
  insert into public.care_adverse_event_history (
    adverse_event_id,patient_id,actor_user_id,actor_kind,action,to_status,
    idempotency_key,occurred_at
  ) values (
    event_row.id,p_patient_id,p_patient_user_id,'care_patient','reported',
    'reported',p_idempotency_key,p_occurred_at
  );
  return event_row;
end;
$$;

create or replace function public.care_assign_adverse_event_owner(
  p_adverse_event_id uuid,
  p_owner_user_id uuid,
  p_owner_role text,
  p_admin_user_id uuid,
  p_idempotency_key text,
  p_occurred_at timestamptz
)
returns public.care_adverse_event_assignments
language plpgsql
security definer
set search_path=''
as $$
declare assignment_row public.care_adverse_event_assignments%rowtype;
declare event_row public.care_adverse_events%rowtype;
begin
  if not exists (
    select 1 from public.care_role_assignments
    where user_id=p_admin_user_id and role='clinical_admin' and revoked_at is null
  ) then raise exception 'care_clinical_admin_required' using errcode='42501'; end if;
  if p_owner_role not in ('clinician','clinical_support') or not exists (
    select 1 from public.care_role_assignments
    where user_id=p_owner_user_id and role=p_owner_role and revoked_at is null
  ) then raise exception 'care_adverse_owner_role_required' using errcode='23514'; end if;
  select * into event_row from public.care_adverse_events
    where id=p_adverse_event_id;
  if not found then raise exception 'care_adverse_event_required' using errcode='23503'; end if;
  select * into assignment_row from public.care_adverse_event_assignments
    where adverse_event_id=p_adverse_event_id and owner_user_id=p_owner_user_id
      and owner_role=p_owner_role and revoked_at is null;
  if found then return assignment_row; end if;
  insert into public.care_adverse_event_assignments (
    adverse_event_id,owner_user_id,owner_role,assigned_by,assigned_at
  ) values (
    p_adverse_event_id,p_owner_user_id,p_owner_role,p_admin_user_id,p_occurred_at
  ) returning * into assignment_row;
  insert into public.care_adverse_event_history (
    adverse_event_id,patient_id,actor_user_id,actor_kind,action,to_status,
    idempotency_key,occurred_at
  ) values (
    event_row.id,event_row.patient_id,p_admin_user_id,'clinical_admin',
    'owner_assigned',event_row.status,p_idempotency_key,p_occurred_at
  );
  return assignment_row;
end;
$$;

create or replace function public.care_apply_adverse_event_action(
  p_adverse_event_id uuid,
  p_actor_user_id uuid,
  p_expected_version integer,
  p_action text,
  p_idempotency_key text,
  p_occurred_at timestamptz
)
returns public.care_adverse_events
language plpgsql
security definer
set search_path=''
as $$
declare event_row public.care_adverse_events%rowtype;
declare owner_role text;
declare next_status text;
declare previous_status text;
begin
  if exists (
    select 1 from public.care_adverse_event_history
    where adverse_event_id=p_adverse_event_id and action=p_action
      and idempotency_key=p_idempotency_key
  ) then
    select * into event_row from public.care_adverse_events where id=p_adverse_event_id;
    return event_row;
  end if;
  select assignment.owner_role into owner_role
    from public.care_adverse_event_assignments assignment
    join public.care_role_assignments role_assignment
      on role_assignment.user_id=assignment.owner_user_id
      and role_assignment.role=assignment.owner_role
      and role_assignment.revoked_at is null
    where assignment.adverse_event_id=p_adverse_event_id
      and assignment.owner_user_id=p_actor_user_id
      and assignment.revoked_at is null;
  if owner_role is null then
    raise exception 'care_assigned_adverse_owner_required' using errcode='42501';
  end if;
  select * into event_row from public.care_adverse_events
    where id=p_adverse_event_id and version=p_expected_version;
  if not found then raise exception 'care_current_adverse_event_required' using errcode='23514'; end if;
  previous_status := event_row.status;
  next_status := case p_action
    when 'acknowledge' then 'acknowledged'
    when 'escalate' then 'escalated'
    when 'close' then 'closed'
    else null end;
  if next_status is null or not (
    (event_row.status='reported' and p_action='acknowledge')
    or (event_row.status in ('reported','acknowledged') and p_action='escalate')
    or (event_row.status in ('acknowledged','escalated') and p_action='close'
      and (event_row.urgency <> 'possible_emergency'
        or event_row.status='escalated'))
  ) then raise exception 'care_invalid_adverse_event_transition' using errcode='23514'; end if;
  update public.care_adverse_events set
    status=next_status,
    acknowledged_at=case when p_action='acknowledge'
      then p_occurred_at else acknowledged_at end,
    escalated_at=case when p_action='escalate'
      then p_occurred_at else escalated_at end,
    closed_at=case when p_action='close'
      then p_occurred_at else closed_at end,
    version=version+1,updated_at=p_occurred_at
    where id=p_adverse_event_id returning * into event_row;
  insert into public.care_adverse_event_history (
    adverse_event_id,patient_id,actor_user_id,actor_kind,action,
    from_status,to_status,idempotency_key,occurred_at
  ) values (
    event_row.id,event_row.patient_id,p_actor_user_id,owner_role,p_action,
    previous_status,next_status,p_idempotency_key,p_occurred_at
  );
  return event_row;
end;
$$;

