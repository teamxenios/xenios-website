#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const EXPECTED_ROW_COUNT = 426;

const CHANNELS = new Map([
  ["ruo research", { group: "research", label: "Research" }],
  ["clinical provider only", { group: "clinical", label: "Clinical / provider review" }],
  ["supplier catalog classification pending", { group: "pending", label: "Classification pending" }],
  ["supplement", { group: "supplement", label: "Supplement" }],
  ["nonclinical topical", { group: "nonclinical", label: "Nonclinical / topical" }],
]);

function readArgs(argv) {
  const result = {};
  for (let index = 0; index < argv.length; index += 1) {
    const value = argv[index];
    if (!value.startsWith("--")) continue;
    result[value.slice(2)] = argv[index + 1];
    index += 1;
  }
  if (!result.reconciliation || !result.out) {
    throw new Error("Usage: generate-xenios-product-education.mjs --reconciliation <private-json> --out <generated-ts>");
  }
  return {
    reconciliation: resolve(result.reconciliation),
    out: resolve(result.out),
  };
}

function clean(value) {
  return String(value ?? "").replace(/\s+/g, " ").trim();
}

function normalize(value) {
  return clean(value)
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

function publicStatus(value) {
  const normalized = normalize(value);
  if (normalized.includes("founder approved") && normalized.includes("ruo")) {
    return "source_authoritative_price";
  }
  if (normalized.includes("clinical approval")) return "clinical_review";
  if (normalized.includes("classification hold")) return "classification_review";
  if (normalized.includes("re source")) return "request_only";
  if (normalized.includes("msrp") || normalized.includes("map hold")) return "price_verification";
  if (normalized.includes("product specific")) return "product_review";
  if (normalized.includes("price on request")) return "price_on_request";
  return "status_review";
}

function sourceReference(row) {
  const identity = {
    sourceRow: row.sourceRow,
    product: clean(row.Product),
    formulation: clean(row["Strength / Formulation"]),
    dosageForm: clean(row["Dosage Form"]),
    channel: clean(row.Channel),
    family: clean(row.Family),
    displayRule: clean(row["Website Display Rule"]),
    pathwayStatus: clean(row["Clinical / Research Status"]),
  };
  return createHash("sha256").update(JSON.stringify(identity)).digest("hex");
}

function quote(value) {
  return JSON.stringify(value);
}

function render(source, products) {
  const lines = [
    "// Generated by scripts/content/generate-xenios-product-education.mjs.",
    "// Customer-safe workbook reconciliation only. Do not edit by hand.",
    "",
    "export const PRODUCT_EDUCATION_SOURCE = {",
    `  workbookSha256: ${quote(clean(source.workbookSha256Expected).toLowerCase())},`,
    `  sheet: ${quote(clean(source.sourceSheet))},`,
    `  sourceRowCount: ${source.rowCount},`,
    `  representedRowCount: ${products.reduce((total, product) => total + product.variants.length, 0)},`,
    `  canonicalBindingCount: ${products.length},`,
    "  channelCounts: {",
    ...Object.entries(source.channelCounts).map(([key, value]) => `    ${quote(key)}: ${value},`),
    "  },",
    "} as const;",
    "",
    "export type ProductEducationChannel = \"research\" | \"clinical\" | \"pending\" | \"supplement\" | \"nonclinical\";",
    "export type ProductEducationPublicStatus =",
    "  | \"source_authoritative_price\"",
    "  | \"clinical_review\"",
    "  | \"classification_review\"",
    "  | \"request_only\"",
    "  | \"price_verification\"",
    "  | \"product_review\"",
    "  | \"price_on_request\"",
    "  | \"status_review\";",
    "",
    "export type ProductEducationVariantBinding = {",
    "  sourceRef: string;",
    "  formulation: string;",
    "  dosageForm: string;",
    "  status: ProductEducationPublicStatus;",
    "};",
    "",
    "export type ProductEducationProductBinding = {",
    "  key: string;",
    "  normalizedName: string;",
    "  displayName: string;",
    "  channel: ProductEducationChannel;",
    "  channelLabel: string;",
    "  family: string;",
    "  variants: readonly ProductEducationVariantBinding[];",
    "};",
    "",
    "export const PRODUCT_EDUCATION_PRODUCTS = [",
  ];

  for (const product of products) {
    lines.push("  {");
    lines.push(`    key: ${quote(product.key)},`);
    lines.push(`    normalizedName: ${quote(product.normalizedName)},`);
    lines.push(`    displayName: ${quote(product.displayName)},`);
    lines.push(`    channel: ${quote(product.channel)},`);
    lines.push(`    channelLabel: ${quote(product.channelLabel)},`);
    lines.push(`    family: ${quote(product.family)},`);
    lines.push("    variants: [");
    for (const variant of product.variants) {
      lines.push("      {");
      lines.push(`        sourceRef: ${quote(variant.sourceRef)},`);
      lines.push(`        formulation: ${quote(variant.formulation)},`);
      lines.push(`        dosageForm: ${quote(variant.dosageForm)},`);
      lines.push(`        status: ${quote(variant.status)},`);
      lines.push("      },");
    }
    lines.push("    ],");
    lines.push("  },");
  }
  lines.push("] as const satisfies readonly ProductEducationProductBinding[];");
  lines.push("");
  return lines.join("\n");
}

async function main() {
  const paths = readArgs(process.argv.slice(2));
  const source = JSON.parse(await readFile(paths.reconciliation, "utf8"));
  if (!Array.isArray(source.rows) || source.rows.length !== EXPECTED_ROW_COUNT || source.rowCount !== EXPECTED_ROW_COUNT) {
    throw new Error(`Expected ${EXPECTED_ROW_COUNT} source rows; received ${source.rows?.length ?? "invalid"}.`);
  }

  const productsByKey = new Map();
  const sourceRefs = new Set();
  const channelCounts = { research: 0, clinical: 0, pending: 0, supplement: 0, nonclinical: 0 };

  for (const row of source.rows) {
    const channel = CHANNELS.get(normalize(row.Channel));
    if (!channel) throw new Error(`Unsupported channel at private source row ${row.sourceRow}.`);
    const displayName = clean(row.Product);
    const normalizedName = normalize(displayName);
    if (!normalizedName) throw new Error(`Missing product identity at private source row ${row.sourceRow}.`);
    const sourceRef = sourceReference(row);
    if (sourceRefs.has(sourceRef)) throw new Error(`Duplicate exact source identity at private source row ${row.sourceRow}.`);
    sourceRefs.add(sourceRef);
    channelCounts[channel.group] += 1;

    const key = `${channel.group}:${normalizedName}`;
    const current = productsByKey.get(key) ?? {
      key,
      normalizedName,
      displayName,
      channel: channel.group,
      channelLabel: channel.label,
      family: clean(row.Family),
      variants: [],
    };
    current.variants.push({
      sourceRef,
      formulation: clean(row["Strength / Formulation"]),
      dosageForm: clean(row["Dosage Form"]),
      status: publicStatus(row._pricingStatusInternal),
    });
    productsByKey.set(key, current);
  }

  const products = [...productsByKey.values()]
    .map((product) => ({
      ...product,
      variants: product.variants.sort((left, right) =>
        `${left.formulation}\u0000${left.dosageForm}\u0000${left.sourceRef}`.localeCompare(
          `${right.formulation}\u0000${right.dosageForm}\u0000${right.sourceRef}`,
        ),
      ),
    }))
    .sort((left, right) => left.key.localeCompare(right.key));

  const output = render({ ...source, channelCounts }, products);
  await writeFile(paths.out, output, "utf8");
  process.stdout.write(
    JSON.stringify({ sourceRows: sourceRefs.size, canonicalBindings: products.length, channelCounts }, null, 2) + "\n",
  );
}

await main();
